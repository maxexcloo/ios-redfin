/* ---- the fake DSP ---- */
static int selector_report = -1;
static size_t resp(uint8_t *out, uint16_t txn)
{
	size_t n = hx(out, canned_resp_t1);
	memcpy(out + 1, &txn, 2);
	return n;
}

static void fake_send(int fd, const uint8_t *d, size_t n)
{
	uint8_t f[2048];
	uint32_t node = 5, port = 9;
	memcpy(f, &node, 4);
	memcpy(f + 4, &port, 4);
	memcpy(f + 8, d, n);
	if (write(fd, f, 8 + n) != (ssize_t)(8 + n))
		_exit(3);
}

static void fake_send_hex(int fd, const char *h)
{
	uint8_t b[2048];
	fake_send(fd, b, hx(b, h));
}

static void fake_dsp(int fd)
{
	uint8_t f[4096], out[256];
	for (;;) {
		ssize_t n = read(fd, f, sizeof(f));
		if (n <= 8)
			_exit(0);
		struct qmi_msg m;
		uint16_t l;
		if (qmi_parse(f + 8, (uint32_t)(n - 8), &m) || m.type != QMI_REQUEST || m.id != 0x20)
			_exit(4);
		const uint8_t *t = qmi_get(&m, 0x01, &l);
		uint16_t pl;
		if (!t || l < 2)
			_exit(5);
		memcpy(&pl, t, 2);
		/* sns_client_request_msg: msg_id (2) and the request payload (4 -> 2) */
		struct pb_rd r, rq;
		struct pb_field fl, g;
		uint32_t msg_id = 0;
		const uint8_t *payload = NULL;
		size_t plen = 0;
		pb_rd_init(&r, t + 2, pl);
		while (pb_next(&r, &fl) == 1) {
			if (fl.num == 2 && fl.wt == PB_FIXED32)
				msg_id = (uint32_t)fl.v;
			if (fl.num == 4 && fl.wt == PB_LEN) {
				pb_rd_init(&rq, fl.data, fl.len);
				while (pb_next(&rq, &g) == 1)
					if (g.num == 2 && g.wt == PB_LEN) {
						payload = g.data;
						plen = g.len;
					}
			}
		}
		if (selector_report >= 0) {
			char receipt = msg_id == SNS_MSG_ATTR_REQ ? 't' :
			    msg_id == SNS_MSG_SENSOR_CONFIG ? 'c' : msg_id == SNS_MSG_DISABLE ? 'd' :
			    msg_id == SNS_MSG_SUID_REQ && plen >= 7 && !memcmp(payload + 2, "accel", 5) ? 'a' : 'x';
			if (write(selector_report, &receipt, 1) != 1)
				_exit(6);
		}
		fake_send(fd, out, resp(out, m.txn));
		switch (msg_id) {
		case SNS_MSG_SUID_REQ:
			if (plen >= 7 && !memcmp(payload + 2, "accel", 5))
				fake_send_hex(fd, canned_suid_accel);
			else if (plen >= 11 && !memcmp(payload + 2, "proximity", 9))
				fake_send_hex(fd, canned_suid_prox);
			else
				fake_send_hex(fd, canned_suid_none);
			break;
		case SNS_MSG_ATTR_REQ:
			fake_send_hex(fd, canned_attr_accel);
			break;
		case SNS_MSG_SENSOR_CONFIG:
			fake_send_hex(fd, canned_data_accel);
			fake_send_hex(fd, canned_data_accel_packed);
			fake_send_hex(fd, canned_err);
			break;
		case SNS_MSG_ONCHANGE_CONFIG:
			fake_send_hex(fd, canned_prox_near);
			break;
		}
	}
}

static void test_exchange(void)
{
	int sv[2];
	/* SOCK_SEQPACKET where there is one (Linux), else datagrams (macOS; frames here stay < 2 KiB) */
	if (socketpair(AF_UNIX, SOCK_SEQPACKET, 0, sv) != 0)
		CHECK(socketpair(AF_UNIX, SOCK_DGRAM, 0, sv) == 0);
	pid_t pid = fork();
	if (pid == 0) {
		close(sv[0]);
		fake_dsp(sv[1]);
	}
	close(sv[1]);
	fcntl(sv[0], F_SETFL, O_NONBLOCK);	/* as /dev/redwood-qrtr is opened */

	struct cap c = { .n = 0 };
	struct sensor_env e = { .out = capture, .out_ctx = &c, .orient = 1, .timeout_ms = 2000 };
	struct sensor s;
	sensor_init(&s, sensor_kind_find("accel"), sv[0], 5, 9);
	CHECK(sensor_lookup(&e, &s) == 0 && s.suid.high == 0x99aabbccddeeff00ull);
	CHECK(s.client_id == 0xc0ffee);
	CHECK(sensor_get_attrs(&e, &s) == 0 && s.attrs.nrates == 3);
	sensor_print_attrs(&s);
	CHECK(sensor_start(&e, &s, 50) == 0 && s.active && s.hz == 50);
	for (int i = 0; i < 20 && (c.n < 4 || !s.last_error); i++)
		sensor_poll(&e, &s, 50);
	CHECK(c.n == 4);
	CHECK(c.m[0].type == MOTION_TYPE_ACCEL && NEAR(c.m[0].v[0], 0.1f) && NEAR(c.m[0].v[1], 9.80665f) &&
	    NEAR(c.m[0].v[2], -0.2f) && c.m[0].flags == 3 && c.m[0].ts_mach == 192000000ull);
	CHECK(c.m[1].type == MOTION_TYPE_ACCEL && c.m[1].ts_mach == 192000000ull + 7680000ull);
	CHECK(c.m[2].type == MOTION_TYPE_ORIENTATION && c.m[2].v[0] == 1.0f);	/* portrait for 0.4 s */
	CHECK(c.m[3].type == MOTION_TYPE_ACCEL && NEAR(c.m[3].v[0], 9.80665f) && NEAR(c.m[3].v[2], 0.5f) &&
	    c.m[3].flags == 2);
	CHECK(s.last_error == 4 && s.count == 3);
	CHECK(sensor_stop(&e, &s) == 0 && !s.active);

	struct sensor p;
	c.n = 0;
	sensor_init(&p, sensor_kind_find("prox"), sv[0], 5, 9);
	CHECK(sensor_lookup(&e, &p) == 0 && p.suid.low == 0x0102030405060708ull);
	CHECK(sensor_start(&e, &p, 0) == 0 && p.hz == 0);
	for (int i = 0; i < 20 && c.n < 1; i++)
		sensor_poll(&e, &p, 50);
	CHECK(c.n == 1 && c.m[0].type == MOTION_TYPE_PROX && c.m[0].v[0] == 1.0f && c.m[0].v[1] == 1000.0f &&
	    c.m[0].flags == 3);

	struct sensor q;
	sensor_init(&q, sensor_kind_find("pressure"), sv[0], 5, 9);
	CHECK(sensor_lookup(&e, &q) == -1 && q.have_suid == -1);

	close(sv[0]);
	usleep(100000);
	int st = 0;
	if (waitpid(pid, &st, WNOHANG) == 0) {	/* a datagram peer sees no EOF */
		kill(pid, SIGTERM);
		waitpid(pid, &st, 0);
		CHECK(WIFSIGNALED(st));
	} else {
		CHECK(WIFEXITED(st) && WEXITSTATUS(st) == 0);
	}
}

/* Registered SUID updates may precede the request ACK and initially contain no sensors. */
static void test_suid_readiness(void)
{
	for (int scenario = 0; scenario < 5; scenario++) {
		int sv[2];
		/* Only the disconnect case uses a stream: no framed replies are sent before EOF. */
		int type = scenario == 4 ? SOCK_STREAM : SOCK_DGRAM;
		CHECK(socketpair(AF_UNIX, type, 0, sv) == 0);
		pid_t pid = fork();
		CHECK(pid >= 0);
		if (pid < 0) {
			close(sv[0]);
			close(sv[1]);
			continue;
		}
		if (pid == 0) {
			close(sv[0]);
			uint8_t request[2048], reply[2048];
			ssize_t n = read(sv[1], request, sizeof(request));
			struct qmi_msg q;
			if (n <= 8 || qmi_parse(request + 8, (uint32_t)(n - 8), &q))
				_exit(4);
			if (scenario == 4) {
				close(sv[1]);
				_exit(0);
			}
			if (scenario < 2) {
				/* Before ACK guarantees even a queued later update must be consumed by wait_for. */
				fake_send_hex(sv[1], canned_suid_empty_accel);
			} else {
				size_t len = hx(reply, canned_suid_accel);
				/* Malformed protobuf data_type tag, with the QMI/event envelope left valid. */
				for (size_t j = 0; j + 7 <= len; j++) {
					if (!memcmp(reply + j, "\x0a\x05" "accel", 7)) {
						reply[j] = 0x0b;
						break;
					}
				}
				fake_send(sv[1], reply, len);
				fake_send_hex(sv[1], canned_suid_prox); /* Valid SUIDs, wrong data type. */
			}
			fake_send(sv[1], reply, resp(reply, q.txn));
			if (scenario == 0 || scenario == 3)
				fake_send_hex(sv[1], canned_suid_accel);
			/* Keep the transport alive: unsuccessful cases must reach the lookup deadline. */
			for (;;)
				pause();
		}
		close(sv[1]);
		fcntl(sv[0], F_SETFL, O_NONBLOCK);
		struct sensor_env e = { .timeout_ms = 100 };
		struct sensor sensor;
		sensor_init(&sensor, sensor_kind_find("accel"), sv[0], 5, 9);
		long began = sensor_now_ms();
		int rc = sensor_lookup(&e, &sensor);
		if (scenario == 0 || scenario == 3) {
			CHECK(rc == 0 && sensor.have_suid == 1 && sensor.nsuids == 1);
			CHECK(sensor.suid.low == 0x1122334455667788ull && sensor.suid.high == 0x99aabbccddeeff00ull);
		} else {
			CHECK(rc == -1 && sensor.have_suid == (scenario == 1 ? -1 : 0));
			if (scenario != 4) {
				CHECK(sensor_now_ms() - began >= e.timeout_ms);
				CHECK(kill(pid, 0) == 0);
			}
		}
		close(sv[0]);
		if (scenario != 4)
			kill(pid, SIGTERM);
		int status;
		CHECK(waitpid(pid, &status, 0) == pid);
		CHECK(scenario == 4 ? WIFEXITED(status) && WEXITSTATUS(status) == 0 :
		    WIFSIGNALED(status) && WTERMSIG(status) == SIGTERM);
	}
}

/* ---- finite CLI streams: service loss is distinct from a quiet sensor ---- */
static int selector_fd = -1, selector_motion_fd = -1;
static int selector_opens, selector_device_opens, selector_marker;
static int selector_stop_setup = 1, selector_open_limit;
static int cli_open(void)
{
	selector_opens++;
	if (selector_fd < 0 || (selector_open_limit && selector_opens > selector_open_limit)) {
		stop_flag = 1;
		errno = ENODEV;
		return -1;
	}
	return dup(selector_fd);
}

static int cli_device_open(const char *path, int flags, ...)
{
	(void)path;
	(void)flags;
	selector_device_opens++;
	if (selector_motion_fd >= 0)
		return dup(selector_motion_fd);
	errno = ENODEV;
	return -1;
}

static int cli_stat(const char *path, struct stat *status)
{
	CHECK(!strcmp(path, "/var/local/sensd.off"));
	(void)status;
	errno = ENOENT;
	return selector_marker ? 0 : -1;
}

static int lookup_case, lookup_calls;
static int cli_lookup(int fd, uint32_t service, uint32_t *node, uint32_t *port)
{
	(void)fd;
	CHECK(service == SNS_QMI_SERVICE);
	lookup_calls++;
	if (selector_fd >= 0 && selector_stop_setup && lookup_calls == 2)
		stop_flag = 1; /* Complete real selected-sensor setup, then leave the daemon before streaming. */
	if (lookup_case == 8 && lookup_calls > 2) {
		errno = ECONNRESET;
		return -1;
	}
	if ((lookup_case == 1 || lookup_case == 6) && lookup_calls > 1) {
		errno = lookup_case == 6 ? ECONNRESET : ENOENT;
		return -1;
	}
	if (lookup_case == 3 || lookup_case == 7) {
		errno = ENOTTY;
		return -1;
	}
	*node = 5;
	*port = lookup_case == 2 && lookup_calls > 1 ? 10 : 9;
	return 0;
}

static void test_cli_liveness(void)
{
	for (int scenario = 0; scenario < 8; scenario++) {
		int sv[2];
		CHECK(socketpair(AF_UNIX, SOCK_STREAM, 0, sv) == 0);
		fcntl(sv[0], F_SETFL, O_NONBLOCK);
		lookup_case = scenario == 5 ? 1 : scenario;
		lookup_calls = 0;
		opt.qrtr_fd = scenario == 3 ? sv[0] : -1;
		opt.secs = 1;
		opt.print = 0;
		stop_flag = 0;
		struct sensor s;
		sensor_init(&s, sensor_kind_find("als"), sv[0], 5, 9);
		s.active = 1;
		s.hz = 0; /* A quiet on-change stream must succeed while its service remains. */
		if (scenario == 4) {
			close(sv[1]);
			sv[1] = -1;
		}
		int rc = run(&s, 1, scenario == 5);
		CHECK(rc == ((scenario == 1 || scenario == 2 || scenario == 4 || scenario == 5 || scenario == 6 || scenario == 7) ? -1 : 0));
		CHECK(s.count == 0);
		CHECK(lookup_calls > ((scenario == 4 || scenario == 7) ? 0 : 1));
		close(sv[0]);
		if (sv[1] >= 0)
			close(sv[1]);
	}
}

static void reset_selector_cli(void)
{
	memset(&opt, 0, sizeof(opt));
	opt.motion_fd = opt.qrtr_fd = -1;
	opt.follow = opt.orient = opt.motion = 1;
	stop_flag = 0;
	lookup_case = lookup_calls = 0;
	selector_fd = selector_motion_fd = -1;
	selector_opens = selector_device_opens = selector_marker = 0;
	selector_stop_setup = 1;
	selector_open_limit = 0;
}

static void test_finite_daemon(void)
{
	for (int disconnected = 0; disconnected < 2; disconnected++) {
		int sv[2], receipts[2];
		if (socketpair(AF_UNIX, SOCK_DGRAM, 0, sv) || pipe(receipts)) {
			CHECK(0);
			return;
		}
		selector_report = receipts[1];
		pid_t pid = fork();
		if (pid == 0) {
			close(receipts[0]);
			signal(SIGTERM, SIG_DFL);
			close(sv[0]);
			fake_dsp(sv[1]);
			_exit(0);
		}
		CHECK(pid > 0);
		if (pid < 0) {
			close(sv[0]); close(sv[1]); close(receipts[0]); close(receipts[1]);
			selector_report = -1;
			return;
		}
		close(sv[1]);
		close(receipts[1]);
		selector_report = -1;
		fcntl(sv[0], F_SETFL, O_NONBLOCK);
		reset_selector_cli();
		selector_fd = sv[0];
		selector_stop_setup = 0;
		selector_open_limit = 2; /* An erroneous restart exits instead of hanging the test. */
		lookup_case = disconnected ? 8 : 0;
		char *args[] = { "sensd", "--daemon", "--only", "accel", "--no-motion", "--no-orient", "--secs", "1", NULL };
		CHECK(sensd_cli_main(8, args) == (disconnected ? 1 : 0));
		CHECK(selector_opens == 2); /* Finite success or service loss must not open a recovery session. */
		CHECK(selector_device_opens == 0);
		close(sv[0]);
		selector_fd = -1;
		kill(pid, SIGTERM);
		int status;
		CHECK(waitpid(pid, &status, 0) == pid && WIFSIGNALED(status) && WTERMSIG(status) == SIGTERM);
		char requests[8];
		ssize_t n = read(receipts[0], requests, sizeof(requests));
		CHECK(disconnected ? n == 2 && !memcmp(requests, "at", 2) : n == 4 && !memcmp(requests, "atcd", 4));
		close(receipts[0]);
	}
}

static void test_daemon_selector(void)
{
	char *unknown[] = { "sensd", "--daemon", "--only", "not-a-sensor", NULL };
	reset_selector_cli();
	CHECK(sensd_cli_main(4, unknown) == 2);
	CHECK(selector_opens == 0 && selector_device_opens == 0);
	char *wrong_mode[] = { "sensd", "--list", "--only", "accel", NULL };
	reset_selector_cli();
	CHECK(sensd_cli_main(4, wrong_mode) == 2);
	CHECK(selector_opens == 0 && selector_device_opens == 0);
	char *missing[] = { "sensd", "--daemon", "--only", NULL };
	reset_selector_cli();
	CHECK(sensd_cli_main(3, missing) == 2);
	CHECK(selector_opens == 0 && selector_device_opens == 0);

	/* Existing alias resolution is reused, without opening hardware when the marker is set. */
	char *alias[] = { "sensd", "--daemon", "--only", "light", "--no-motion", "--no-orient", NULL };
	reset_selector_cli();
	selector_marker = 1;
	CHECK(sensd_cli_main(6, alias) == 0 && opt.only == sensor_kind_find("als"));
	CHECK(selector_opens == 0 && selector_device_opens == 0);

	/* The real daemon discovers SNS and performs the selected sensor's real SUID/attribute exchange. */
	int sv[2];
	if (socketpair(AF_UNIX, SOCK_DGRAM, 0, sv) != 0) {
		CHECK(0);
		return;
	}
	int receipts[2];
	if (pipe(receipts) != 0) {
		CHECK(0);
		close(sv[0]);
		close(sv[1]);
		return;
	}
	selector_report = receipts[1];
	pid_t pid = fork();
	if (pid < 0) {
		CHECK(pid >= 0);
		close(sv[0]);
		close(sv[1]);
		close(receipts[0]);
		close(receipts[1]);
		selector_report = -1;
		return;
	}
	if (pid == 0) {
		close(receipts[0]);
		signal(SIGTERM, SIG_DFL);
		close(sv[0]);
		fake_dsp(sv[1]);
		_exit(0);
	}
	close(sv[1]);
	close(receipts[1]);
	selector_report = -1;
	fcntl(sv[0], F_SETFL, O_NONBLOCK);
	reset_selector_cli();
	selector_fd = sv[0];
	char *selected[] = { "sensd", "--daemon", "--only", "accel", "--no-motion", "--no-orient", NULL };
	CHECK(sensd_cli_main(6, selected) == 0);
	/* One SNS discovery port and one selected-sensor setup port; unselected setup would open more. */
	CHECK(selector_opens == 2 && lookup_calls == 2);
	CHECK(selector_device_opens == 0); /* --no-motion must cover the daemon setup path too. */
	CHECK(opt.only == sensor_kind_find("accel"));
	close(sv[0]);
	selector_fd = -1;
	kill(pid, SIGTERM);
	int status;
	CHECK(waitpid(pid, &status, 0) == pid && WIFSIGNALED(status) && WTERMSIG(status) == SIGTERM);
	char requests[8];
	CHECK(read(receipts[0], requests, sizeof(requests)) == 2 && !memcmp(requests, "at", 2));
	close(receipts[0]);
}

static void test_motion_open_policy(void)
{
	reset_selector_cli();
	opt.motion = 0;
	open_motion();
	CHECK(selector_device_opens == 0 && opt.motion_fd == -1);
	opt.motion = 1;
	open_motion();
	open_motion();
	CHECK(selector_device_opens == 2 && opt.motion_fd == -1); /* Failed opens remain retryable. */
	int sv[2];
	if (socketpair(AF_UNIX, SOCK_DGRAM, 0, sv) != 0) {
		CHECK(0);
		return;
	}
	selector_motion_fd = sv[0];
	open_motion();
	CHECK(selector_device_opens == 3 && opt.motion_fd >= 0);
	open_motion();
	CHECK(selector_device_opens == 3); /* Keep the established descriptor once open. */
	if (opt.motion_fd >= 0)
		close(opt.motion_fd);
	close(sv[0]);
	close(sv[1]);
	selector_motion_fd = -1;
	opt.motion_fd = -1;
}

