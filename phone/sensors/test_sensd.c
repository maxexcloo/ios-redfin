	sensor_init(&s, sensor_kind_find("mag"), -1, 5, 9);
	CHECK(!strcmp(s.k->alias, "compass"));
	n = hx(b, canned_suid_none);
	sensor_init(&s, sensor_kind_find("pressure"), -1, 5, 9);
	sensor_handle(&e, &s, b, n);
	CHECK(s.have_suid == -1);

	CHECK(sensor_orientation_of(0, 9.8f, 0) == 1 && sensor_orientation_of(0, -9.8f, 0) == 2);
